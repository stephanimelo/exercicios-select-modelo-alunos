-- A1) Selecionar todos os alunos cadastrados
SELECT * FROM TB_ALUNO;

-- A2) Nomes de disciplina com nota minima maior que 5
SELECT NOME_DISCIPLINA
FROM TB_DISCIPLINA
WHERE NOTA_MINIMA_DISCIPLINA > 5;

-- A3) Disciplinas com nota minima entre 3 e 5
SELECT *
FROM TB_DISCIPLINA
WHERE NOTA_MINIMA_DISCIPLINA BETWEEN 3 AND 5;

-- B1) Alunos em ordem alfabetica, com numero da classe
SELECT NOME_ALUNO, ID_CLASSE
FROM TB_ALUNO
ORDER BY NOME_ALUNO;

-- B2) Mesmo item anterior, ordenado por codigo do aluno de forma descendente
SELECT NOME_ALUNO, ID_CLASSE
FROM TB_ALUNO
ORDER BY COD_ALUNO DESC;

-- B3) Alunos que cursam Matematica E Portugues, agrupados por aluno e disciplina
SELECT COD_ALUNO, ID_DISCIPLINA
FROM TB_ALUNO_DISCIPLINA
WHERE COD_ALUNO IN (
    SELECT COD_ALUNO
    FROM TB_ALUNO_DISCIPLINA
    WHERE ID_DISCIPLINA IN ('MAT', 'POR')
    GROUP BY COD_ALUNO
    HAVING COUNT(DISTINCT ID_DISCIPLINA) = 2
)
GROUP BY COD_ALUNO, ID_DISCIPLINA;

-- C1) Nomes de alunos que cursam Portugues ou Matematica
SELECT DISTINCT A.NOME_ALUNO
FROM TB_ALUNO A
JOIN TB_ALUNO_DISCIPLINA AD ON A.COD_ALUNO = AD.COD_ALUNO
WHERE AD.ID_DISCIPLINA IN ('MAT', 'POR');

-- C2) Nomes e enderecos de alunos que cursam Fisica
SELECT DISTINCT A.NOME_ALUNO, A.END_ALUNO
FROM TB_ALUNO A
JOIN TB_ALUNO_DISCIPLINA AD ON A.COD_ALUNO = AD.COD_ALUNO
WHERE AD.ID_DISCIPLINA = 'FIS';

-- C3) Nomes de alunos que cursam Fisica e o andar da classe
SELECT DISTINCT A.NOME_ALUNO,
       'andar ' + CAST(C.ID_ANDAR AS VARCHAR(10)) AS ANDAR
FROM TB_ALUNO A
JOIN TB_ALUNO_DISCIPLINA AD ON A.COD_ALUNO = AD.COD_ALUNO
JOIN TB_CLASSE C ON A.ID_CLASSE = C.ID_CLASSE
WHERE AD.ID_DISCIPLINA = 'FIS';

-- D1) Professores com suas disciplinas, incluindo os que nao lecionam nenhuma
SELECT P.NOME_PROFESSOR, D.NOME_DISCIPLINA
FROM TB_PROFESSOR P
LEFT JOIN TB_DISCIPLINA D ON P.ID_PROFESSOR = D.ID_PROFESSOR;

-- E1) Professores que lecionaram para alunos do Piaui, classe no 3 andar
SELECT NOME_PROFESSOR
FROM TB_PROFESSOR
WHERE ID_PROFESSOR IN (
    SELECT ID_PROFESSOR
    FROM TB_DISCIPLINA
    WHERE ID_DISCIPLINA IN (
        SELECT ID_DISCIPLINA
        FROM TB_ALUNO_DISCIPLINA
        WHERE COD_ALUNO IN (
            SELECT COD_ALUNO
            FROM TB_ALUNO
            WHERE SIGLA_ESTADO = 'PI'
            AND ID_CLASSE IN (
                SELECT ID_CLASSE FROM TB_CLASSE WHERE ID_ANDAR = 3
            )
        )
    )
);
