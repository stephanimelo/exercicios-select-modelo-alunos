CREATE DATABASE db_curso;
GO
USE db_curso;
GO

CREATE TABLE TB_ESTADO (
    SIGLA_ESTADO CHAR(2) NOT NULL,
    NOME_ESTADO VARCHAR(40)
);

CREATE TABLE TB_CLASSE (
    ID_CLASSE SMALLINT NOT NULL,
    ID_ANDAR SMALLINT
);

CREATE TABLE TB_PROFESSOR (
    ID_PROFESSOR CHAR(3) NOT NULL,
    NOME_PROFESSOR VARCHAR(30)
);

CREATE TABLE TB_ALUNO (
    COD_ALUNO SMALLINT NOT NULL,
    NOME_ALUNO VARCHAR(40),
    END_ALUNO VARCHAR(30),
    SIGLA_ESTADO CHAR(2),
    ID_CLASSE SMALLINT
);

CREATE TABLE TB_DISCIPLINA (
    ID_DISCIPLINA CHAR(3) NOT NULL,
    NOME_DISCIPLINA VARCHAR(15),
    ID_PROFESSOR CHAR(3),
    NOTA_MINIMA_DISCIPLINA SMALLINT
);

CREATE TABLE TB_ALUNO_DISCIPLINA (
    COD_ALUNO SMALLINT NOT NULL,
    ID_DISCIPLINA CHAR(3) NOT NULL,
    NOTA_ALUNO SMALLINT
);
GO

-- Chaves primárias
ALTER TABLE TB_ESTADO ADD CONSTRAINT PK_TB_ESTADO PRIMARY KEY (SIGLA_ESTADO);
ALTER TABLE TB_CLASSE ADD CONSTRAINT PK_TB_CLASSE PRIMARY KEY (ID_CLASSE);
ALTER TABLE TB_PROFESSOR ADD CONSTRAINT PK_TB_PROFESSOR PRIMARY KEY (ID_PROFESSOR);
ALTER TABLE TB_ALUNO ADD CONSTRAINT PK_TB_ALUNO PRIMARY KEY (COD_ALUNO);
ALTER TABLE TB_DISCIPLINA ADD CONSTRAINT PK_TB_DISCIPLINA PRIMARY KEY (ID_DISCIPLINA);
ALTER TABLE TB_ALUNO_DISCIPLINA ADD CONSTRAINT PK_TB_ALUNO_DISCIPLINA PRIMARY KEY (COD_ALUNO, ID_DISCIPLINA);
GO

-- Chaves estrangeiras
ALTER TABLE TB_ALUNO ADD CONSTRAINT FK_TB_ALUNO_TB_ESTADO FOREIGN KEY (SIGLA_ESTADO) REFERENCES TB_ESTADO(SIGLA_ESTADO);
ALTER TABLE TB_ALUNO ADD CONSTRAINT FK_TB_ALUNO_TB_CLASSE FOREIGN KEY (ID_CLASSE) REFERENCES TB_CLASSE(ID_CLASSE);
ALTER TABLE TB_DISCIPLINA ADD CONSTRAINT FK_TB_DISCIPLINA_TB_PROFESSOR FOREIGN KEY (ID_PROFESSOR) REFERENCES TB_PROFESSOR(ID_PROFESSOR);
ALTER TABLE TB_ALUNO_DISCIPLINA ADD CONSTRAINT FK_TB_ALUNO_DISCIPLINA_TB_ALUNO FOREIGN KEY (COD_ALUNO) REFERENCES TB_ALUNO(COD_ALUNO);
ALTER TABLE TB_ALUNO_DISCIPLINA ADD CONSTRAINT FK_TB_ALUNO_DISCIPLINA_TB_DISCIPLINA FOREIGN KEY (ID_DISCIPLINA) REFERENCES TB_DISCIPLINA(ID_DISCIPLINA);
GO

